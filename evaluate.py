        "# ARTI 403 — Group 2\n",
        "#  Evaluation Metrics for PCB Defect Detection\n",
        "# My contribution:\n",
        "# I evaluate the bounding boxes produced by the PCB defect detector.\n",
        "# I compare them with the DeepPCB ground-truth boxes using IoU and\n",
        "# calculate TP, FP, FN, precision, recall, and F1.\n",
        "# I also report localization recall separately for Open and Short defects.\n",
        "\n",
        "IOU_THRESHOLD = 0.33\n",
        "\n",
        "\n",
        "def iou(box_a, box_b):\n",
        "    \"\"\"Calculate the intersection over union of two bounding boxes.\"\"\"\n",
        "    ax1, ay1, ax2, ay2 = box_a\n",
        "    bx1, by1, bx2, by2 = box_b\n",
        "\n",
        "    width = max(0, min(ax2, bx2) - max(ax1, bx1))\n",
        "    height = max(0, min(ay2, by2) - max(ay1, by1))\n",
        "    intersection = width * height\n",
        "\n",
        "    area_a = (ax2 - ax1) * (ay2 - ay1)\n",
        "    area_b = (bx2 - bx1) * (by2 - by1)\n",
        "    union = area_a + area_b - intersection\n",
        "\n",
        "    return intersection / union if union > 0 else 0.0\n",
        "\n",
        "\n",
        "def count_matches(pred, gt):\n",
        "    \"\"\"Count correct detections, false detections, and missed defects.\"\"\"\n",
        "    # DeepPCB class IDs: 1 = Open, 2 = Short.\n",
        "    labels = {\"1\": \"Open\", \"open\": \"Open\", \"2\": \"Short\", \"short\": \"Short\"}\n",
        "\n",
        "    targets = []\n",
        "    for x1, y1, x2, y2, defect_type in gt:\n",
        "        defect = labels.get(str(defect_type).strip().lower())\n",
        "        if defect is not None:\n",
        "            targets.append(((x1, y1, x2, y2), defect))\n",
        "\n",
        "    # Collect valid matches and check the highest IoU first.\n",
        "    candidates = []\n",
        "    for pred_index, pred_box in enumerate(pred):\n",
        "        for gt_index, (gt_box, _) in enumerate(targets):\n",
        "            overlap = iou(pred_box, gt_box)\n",
        "            if overlap > IOU_THRESHOLD:\n",
        "                candidates.append((-overlap, pred_index, gt_index))\n",
        "\n",
        "    counts = {\n",
        "        \"Open\": {\"TP\": 0, \"FP\": None, \"FN\": 0},\n",
        "        \"Short\": {\"TP\": 0, \"FP\": None, \"FN\": 0},\n",
        "    }\n",
        "    matched_pred = set()\n",
        "    matched_gt = set()\n",
        "\n",
        "    for _, pred_index, gt_index in sorted(candidates):\n",
        "        # Each predicted box and each true box can be used only once.\n",
        "        if pred_index not in matched_pred and gt_index not in matched_gt:\n",
        "            matched_pred.add(pred_index)\n",
        "            matched_gt.add(gt_index)\n",
        "            defect = targets[gt_index][1]\n",
        "            counts[defect][\"TP\"] += 1\n",
        "\n",
        "    for gt_index, (_, defect) in enumerate(targets):\n",
        "        if gt_index not in matched_gt:\n",
        "            counts[defect][\"FN\"] += 1\n",
        "\n",
        "    counts[\"Combined\"] = {\n",
        "        \"TP\": len(matched_gt),\n",
        "        \"FP\": len(pred) - len(matched_pred),\n",
        "        \"FN\": len(targets) - len(matched_gt),\n",
        "    }\n",
        "    return counts\n",
        "\n",
        "\n",
        "def calculate_metrics(counts):\n",
        "    \"\"\"Calculate precision, recall, and F1 from the detection counts.\"\"\"\n",
        "    tp, fp, fn = counts[\"TP\"], counts[\"FP\"], counts[\"FN\"]\n",
        "    recall = tp / (tp + fn) if tp + fn else 0.0\n",
        "\n",
        "    # The detector does not predict class labels, so class-specific\n",
        "    # false positives, precision, and F1 are not applicable.\n",
        "    if fp is None:\n",
        "        precision = None\n",
        "        f1 = None\n",
        "    else:\n",
        "        precision = tp / (tp + fp) if tp + fp else 0.0\n",
        "        f1 = (\n",
        "            2 * precision * recall / (precision + recall)\n",
        "            if precision + recall\n",
        "            else 0.0\n",
        "        )\n",
        "\n",
        "    return {**counts, \"P\": precision, \"R\": recall, \"F1\": f1}\n",
        "\n",
        "\n",
        "def evaluate(pred, gt):\n",
        "    \"\"\"Return the combined metrics for a single image.\"\"\"\n",
        "    return calculate_metrics(count_matches(pred, gt)[\"Combined\"])\n",
        "\n",
        "\n",
        "def evaluate_dataset(samples):\n",
        "    \"\"\"Sum counts across all images before calculating the metrics.\"\"\"\n",
        "    totals = count_matches([], [])\n",
        "\n",
        "    for pred, gt in samples:\n",
        "        image_counts = count_matches(pred, gt)\n",
        "        for group, counts in image_counts.items():\n",
        "            for metric, value in counts.items():\n",
        "                if value is not None:\n",
        "                    totals[group][metric] += value\n",
        "\n",
        "    return {\n",
        "        group: calculate_metrics(counts)\n",
        "        for group, counts in totals.items()\n",
        "    }\n",
        "\n",
        "\n",
