"""## 2. Functions"""

import os
import cv2
from collections import Counter

# Folder that contains trainval.txt and test.txt
ROOT = "DeepPCB/PCBData"

NAMES = {1: "open", 2: "short", 3: "mousebite", 4: "spur", 5: "copper", 6: "pin-hole"}
KEEP = {1, 2}  # we only use Open and Short


def list_samples(split="train"):
    """Return a list of samples: (image_path_without_extension, annotation_path)."""
    fname = "trainval.txt" if split == "train" else "test.txt"
    samples = []
    with open(os.path.join(ROOT, fname)) as f:
        for line in f:
            parts = line.replace(",", " ").split()
            if len(parts) >= 2:
                samples.append((parts[0].replace(".jpg", ""), parts[1]))
    return samples


def load_pair(sample):
    """Return (defective image, defect-free template, ground-truth boxes)."""
    img_path, ann_path = sample
    test = cv2.imread(os.path.join(ROOT, img_path + "_test.jpg"), cv2.IMREAD_GRAYSCALE)
    temp = cv2.imread(os.path.join(ROOT, img_path + "_temp.jpg"), cv2.IMREAD_GRAYSCALE)

    boxes = []
    with open(os.path.join(ROOT, ann_path)) as f:
        for line in f:
            p = line.replace(",", " ").split()
            if len(p) == 5 and int(p[4]) in KEEP:
                boxes.append((int(p[0]), int(p[1]), int(p[2]), int(p[3]), int(p[4])))
    return test, temp, boxes


def stats(split="train"):
    """Count how many defects of each type (Open / Short) are in the split."""
    counter = Counter()
    for s in list_samples(split):
        _, _, boxes = load_pair(s)
        counter.update(NAMES[b[4]] for b in boxes)
    return counter


def save_example(sample, out_dir="examples", name="example"):
    """Save template, test, and test-with-GT-boxes images (for the report)."""
    os.makedirs(out_dir, exist_ok=True)
    test, temp, boxes = load_pair(sample)

    vis = cv2.cvtColor(test, cv2.COLOR_GRAY2BGR)
    for x1, y1, x2, y2, t in boxes:
        cv2.rectangle(vis, (x1, y1), (x2, y2), (0, 255, 0), 2)
        cv2.putText(vis, NAMES[t], (x1, max(y1 - 4, 10)),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 1)

    cv2.imwrite(os.path.join(out_dir, f"{name}_template.png"), temp)
    cv2.imwrite(os.path.join(out_dir, f"{name}_test.png"), test)
    cv2.imwrite(os.path.join(out_dir, f"{name}_gt.png"), vis)

"""## 3. Statistics (for the Dataset section table)
Expected: 1000 train pairs and 500 test pairs.
"""

for sp in ("train", "test"):
    samples = list_samples(sp)
    print(f"{sp}: {len(samples)} pairs, defects = {dict(stats(sp))}")

"""## 4. Save 3 examples for the report"""

train_samples = list_samples("train")
for i in range(3):
    save_example(train_samples[i], name=f"example{i + 1}")
print("Saved 3 examples in the 'examples' folder.")

